const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, 'js/history-budget.js'), 'utf8').replace(/export /g, ''), context);
const { trimHistory } = context;
let undo = ['old', 'mid', 'new'], redo = ['later'];
trimHistory(undo, redo, undo, 12);
assert.deepEqual(undo, ['mid', 'new']); assert.deepEqual(redo, []);
undo = ['old']; redo = ['latest'];
trimHistory(undo, redo, redo, 12);
assert.deepEqual(undo, []); assert.deepEqual(redo, ['latest']);
undo = ['oversized']; redo = [];
trimHistory(undo, redo, undo, 2);
assert.equal(undo.length, 0, 'One giant snapshot must not exceed the budget');
undo = Array.from({ length: 40 }, (_, i) => String(i)); redo = [];
trimHistory(undo, redo);
assert.equal(undo.length, 30); assert.equal(undo[0], '10');
console.log('PASS combined history byte limit, direction preference, oversized entry and 30-entry bounds');
